-- Pilot policies: authenticated workshop users can operate the internal app.
-- Public customer approval is NOT exposed through these tables; it goes through Edge Functions.
do $$
declare
  t text;
begin
  foreach t in array array['customers','vehicles','work_orders','inspection_photos','budget_revisions','budget_items','approval_tokens','approvals','activity_log']
  loop
    execute format('drop policy if exists authenticated_all on public.%I', t);
    execute format(
      'create policy authenticated_all on public.%I for all to authenticated using (true) with check (true)',
      t
    );
  end loop;
end $$;

insert into storage.buckets (id, name, public)
values ('oficina-evidence','oficina-evidence',false)
on conflict (id) do update set public=false;

-- Only authenticated internal users can read/write normal evidence directly.
drop policy if exists "authenticated evidence read" on storage.objects;
create policy "authenticated evidence read"
on storage.objects for select to authenticated
using (bucket_id='oficina-evidence');

drop policy if exists "authenticated evidence write" on storage.objects;
create policy "authenticated evidence write"
on storage.objects for insert to authenticated
with check (bucket_id='oficina-evidence');

drop policy if exists "authenticated evidence update" on storage.objects;
create policy "authenticated evidence update"
on storage.objects for update to authenticated
using (bucket_id='oficina-evidence')
with check (bucket_id='oficina-evidence');
